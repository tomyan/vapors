//! The clip table (flat-scene F3, `docs/plans/flat-scene-f3.md`): one
//! storage buffer of clip entries the fragment stage reads, each
//! instance naming the innermost clip it is drawn under, each entry its
//! frame's transform entry and the next clip outward. A table of
//! [`ClipEntry`] values ([`Table`]); entry 0 is no clip.

use crate::table::Table;
use crate::table_entries::EntryValue;
use crate::{FrameEncoder, Holding};

/// One clip: a rounded rectangle in device pixels in its frame's space,
/// that frame's entry in the transform table, the next clip outward (0
/// for none), and whether it is relative to the instance's row as well
/// (a clip inside a lane row, its rectangle relative to the row).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ClipEntry {
    /// Left, top, right, bottom.
    pub rect: [f32; 4],
    /// Top-left, top-right, bottom-right, bottom-left, circular.
    pub radii: [f32; 4],
    /// Its frame's entry in the transform table.
    pub frame: u32,
    /// The next clip outward; 0 for none.
    pub parent: u32,
    /// Relative to the instance's row in its batch's range too.
    pub row_relative: bool,
    /// Given back: the poison, which covers nothing (`clip.wgsl` tests
    /// this bit, as a shader compiler may assume no NaN).
    pub given_back: bool,
}

impl ClipEntry {
    /// A rectangle in `frame`'s space with no corners, no parent, not
    /// relative to a row.
    #[must_use]
    pub fn rect(rect: [f32; 4], frame: u32) -> Self {
        Self {
            rect,
            radii: [0.0; 4],
            frame,
            parent: 0,
            row_relative: false,
            given_back: false,
        }
    }
}

impl EntryValue for ClipEntry {
    const BYTES: u64 = 48;
    // entry 0, no clip: the shader stops at index 0 before reading it
    const FIRST: Self = Self {
        rect: [0.0; 4],
        radii: [0.0; 4],
        frame: 0,
        parent: 0,
        row_relative: false,
        given_back: false,
    };
    // Relaxed backstop (flat-scene-f3.md item 11): a given-back entry
    // covers nothing, so a stale reference the CPU checks missed draws
    // nothing rather than another box's clip; missing content with no
    // error, as the GPU cannot report it. Retired if the GPU gains a way
    // to report it.
    const POISON: Option<Self> = Some(Self {
        rect: [f32::NAN; 4],
        radii: [0.0; 4],
        frame: 0,
        parent: 0,
        row_relative: false,
        given_back: true,
    });

    fn write_bytes(&self, out: &mut Vec<u8>) {
        let floats = self.rect.iter().chain(&self.radii);
        out.extend(floats.flat_map(|v| v.to_le_bytes()));
        let flags = u32::from(self.row_relative) | u32::from(self.given_back) << 1;
        let words = [self.frame, self.parent, flags, 0];
        out.extend(words.iter().flat_map(|v| v.to_le_bytes()));
    }

    fn holding(limit: &'static str) -> Holding {
        Holding::ClipEntries { limit }
    }
}

/// The clip table.
pub type ClipTable = Table<ClipEntry>;

impl ClipTable {
    /// Sets entry `at` to `entry`, writing it when it changed, for the
    /// draws of `frame`.
    ///
    /// # Panics
    ///
    /// When the entry, already written for `frame`, would change
    /// (`table_entries.rs` `Entries::set`).
    pub fn set(&mut self, frame: &FrameEncoder, queue: &wgpu::Queue, at: u32, entry: ClipEntry) {
        self.set_values(frame, queue, (at, &[entry]));
    }

    /// What entry `at` holds.
    #[must_use]
    pub fn entry(&self, at: u32) -> ClipEntry {
        self.get(at)
    }
}

/// The WGSL the clip shader is concatenated after: the chain's bound,
/// [`vapors_scene::MAX_CLIP_CHAIN`], one number for the paint refusal and
/// the shader's loop.
#[must_use]
pub fn clip_prelude() -> String {
    format!(
        "// generated by clip_table.rs from vapors_scene::MAX_CLIP_CHAIN\nconst MAX_CLIP_CHAIN: u32 = {}u;\n",
        vapors_scene::MAX_CLIP_CHAIN
    )
}

/// The clip shader a 2D pipeline's shader is concatenated with: the
/// prelude ([`clip_prelude`]), `clip.wgsl`, and the clip table declared
/// at `binding` of `group`, the pipeline's own place for it. The
/// pipeline's shader declares `transforms`, the transform table.
#[must_use]
pub fn clip_source(group: u32, binding: u32) -> String {
    format!(
        "{}{}@group({group}) @binding({binding}) var<storage, read> clips: array<Clip>;\n",
        clip_prelude(),
        include_str!("clip.wgsl")
    )
}

