//! `cargo xtask gpu-info`: write `docs/gpu-limits.md` from what wgpu
//! reports on this machine. Generated, never typed, so it is always
//! what the adapter actually said.

use std::fs;
use std::process::{Command, ExitCode};

const OUTPUT: &str = "docs/gpu-limits.md";

/// Run the `gpu_info` example and write its table to `docs/gpu-limits.md`.
pub fn run() -> ExitCode {
    let output = Command::new("cargo")
        .args([
            "run",
            "-q",
            "-p",
            "vapors-gpu-harness",
            "--example",
            "gpu_info",
        ])
        .output();
    let output = match output {
        Ok(output) if output.status.success() => output,
        Ok(output) => return fail(&String::from_utf8_lossy(&output.stderr)),
        Err(error) => return fail(&format!("could not run cargo: {error}")),
    };
    let table = String::from_utf8_lossy(&output.stdout);
    let host = hostname().unwrap_or_else(|| "unknown host".to_owned());
    if let Err(error) =
        fs::create_dir_all("docs").and_then(|()| fs::write(OUTPUT, document(&host, &table)))
    {
        return fail(&format!("could not write {OUTPUT}: {error}"));
    }
    println!("ok   gpu-info  wrote {OUTPUT} for {host}");
    ExitCode::SUCCESS
}

fn document(host: &str, table: &str) -> String {
    format!(
        "# GPU adapters and limits\n\n\
         Generated by `cargo xtask gpu-info` on `{host}`. Do not edit; rerun.\n\n\
         {table}\n\
         The `gpu` test tier runs on the adapter named by `VAPORS_GPU_ADAPTER`,\n\
         or the first hardware adapter when unset. CI uses `llvmpipe`.\n"
    )
}

fn hostname() -> Option<String> {
    let output = Command::new("hostname").output().ok()?;
    let name = String::from_utf8_lossy(&output.stdout).trim().to_owned();
    (!name.is_empty()).then_some(name)
}

fn fail(message: &str) -> ExitCode {
    println!("FAIL gpu-info: {}", message.trim());
    ExitCode::FAILURE
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn document_names_the_host_and_embeds_the_table() {
        // Given
        let table = "| a |\n|---|\n| b |\n";

        // When
        let text = document("box", table);

        // Then
        assert!(text.contains("on `box`"));
        assert!(text.contains("| b |"));
        assert!(text.starts_with("# GPU adapters and limits"));
    }
}
